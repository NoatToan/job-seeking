// Regenerates src/source-icons.css from src/assets/sources/* and simple-icons.
//   node packages/ui/scripts/build-source-icons.mjs
// Each brand mark becomes a data: URI on one CSS rule, so a page with 60 job rows ships every
// mark once (in the stylesheet) instead of once per row, and nothing is fetched at runtime
// (CSP img-src already allows data:). Which file each brand uses: src/assets/sources/README.md.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { siGlassdoor, siGreenhouse, siUpwork, siYcombinator } from "simple-icons";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const assets = join(root, "src/assets/sources");

const simple = (icon) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path fill="#${icon.hex}" d="${icon.path}"/></svg>`;
const svgUri = (svg) => `data:image/svg+xml,${encodeURIComponent(svg.trim()).replace(/'/g, "%27")}`;
const fileUri = (name) =>
  name.endsWith(".svg")
    ? svgUri(readFileSync(join(assets, name), "utf8"))
    : `data:image/png;base64,${readFileSync(join(assets, name)).toString("base64")}`;

// Keep in sync with SOURCE_ICONS in src/components/source-icon.tsx (a test checks both ways).
const ICONS = {
  linkedin: fileUri("linkedin.png"),
  seek: fileUri("seek.png"),
  arc: fileUri("arc.png"),
  lever: fileUri("lever.png"),
  ashby: fileUri("ashby.png"),
  remotive: fileUri("remotive.png"),
  weworkremotely: fileUri("weworkremotely.png"),
  himalayas: fileUri("himalayas.svg"),
  adzuna: fileUri("adzuna.svg"),
  glassdoor: svgUri(simple(siGlassdoor)),
  greenhouse: svgUri(simple(siGreenhouse)),
  upwork: svgUri(simple(siUpwork)),
  ycombinator: svgUri(simple(siYcombinator)),
};

const rules = Object.entries(ICONS)
  .map(([id, uri]) => `.ujc-source-icon[data-source="${id}"] {\n  background-image: url("${uri}");\n}`)
  .join("\n");

const css = `/* GENERATED by packages/ui/scripts/build-source-icons.mjs — do not edit by hand. */
/* Job-source brand marks for <SourceIcon> (packages/ui/src/components/source-icon.tsx). */
.ujc-source-icon {
  display: inline-block;
  flex-shrink: 0;
  vertical-align: middle;
  background-position: center;
  background-repeat: no-repeat;
  background-size: contain;
  border-radius: 22%;
  /* Hairline so full-bleed marks (Arc's black square, WWR's white one) keep an edge on either theme. */
  box-shadow: inset 0 0 0 1px var(--ujc-separator);
  /* Logos are attribution, not decoration: keep them in Windows high-contrast mode too. */
  forced-color-adjust: none;
}
/* Marks without their own background sit on a white tile, so a purple or navy mark stays
   legible on the dark theme and every icon reads as the same-sized square. */
.ujc-source-icon[data-tile] {
  background-color: #fff;
  background-size: 74%;
}
${rules}
`;

writeFileSync(join(root, "src/source-icons.css"), css);
console.log(`wrote src/source-icons.css (${css.length} bytes, ${Object.keys(ICONS).length} icons)`);
